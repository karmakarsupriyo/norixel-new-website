-- Run this SQL in Supabase SQL Editor.
create table if not exists public.creator_applications (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null,
  phone text not null,
  location text not null,
  platform text not null,
  category text not null,
  profile_url text not null,
  followers bigint,
  average_views bigint,
  bio text,
  status text not null default 'pending' check (status in ('pending','reviewing','approved','rejected')),
  created_at timestamptz not null default now()
);

alter table public.creator_applications enable row level security;

drop policy if exists "Public can submit creator applications" on public.creator_applications;
create policy "Public can submit creator applications"
on public.creator_applications
for insert
to anon, authenticated
with check (status = 'pending');

-- Do not create public SELECT, UPDATE or DELETE policies.
